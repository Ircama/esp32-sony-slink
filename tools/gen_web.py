"""Turns the files of main/web/ (page, manifest, service worker, icons) into main/web_page.c (byte arrays + table), so the portal is part of the firmware.
Runs automatically before every PlatformIO build (extra_scripts = pre:tools/gen_web.py) and can also be run by hand:
    python tools/gen_web.py
"""
import gzip, hashlib, os

try:
    Import("env")                       # noqa: F821  (PlatformIO SCons)
    root = env.subst("$PROJECT_DIR")    # noqa: F821
except NameError:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

src = os.path.join(root, "main", "web", "index.html")
dst = os.path.join(root, "main", "web_page.c")

ASSETS = [  # (file in main/web, URL, MIME type, Cache-Control)
    ("index.html", "/", "text/html; charset=utf-8", "no-store"),     # never kept by a browser: a stale page (old script) is worse than 100 KB over the LAN
    ("help.html", "/help.html", "text/html; charset=utf-8", "no-cache"),
    ("manifest.webmanifest", "/manifest.webmanifest", "application/manifest+json", "no-cache"),
    ("sw.js", "/sw.js", "text/javascript; charset=utf-8", "no-cache"),
    ("icon.svg", "/icon.svg", "image/svg+xml", "public, max-age=86400"),
    ("icon-192.png", "/icon-192.png", "image/png", "public, max-age=86400"),
    ("icon-512.png", "/icon-512.png", "image/png", "public, max-age=86400"),
    ("icon-maskable-512.png", "/icon-maskable-512.png", "image/png", "public, max-age=86400"),
    ("apple-touch-icon.png", "/apple-touch-icon.png", "image/png", "public, max-age=86400"),
]


def array(name, data):
    out = ["static const unsigned char %s[] = {" % name]
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("  0\n};")
    return out


lines = ["/* GENERATED by tools/gen_web.py from main/web/ - do not edit */",
         "#include <stddef.h>",
         "#include \"web_page.h\""]
table = []
for n, (f, url, mime, cache) in enumerate(ASSETS):
    data = open(os.path.join(root, "main", "web", f), "rb").read()
    if f == "index.html":                                   # the page knows its own build; the device reports the one it serves (GET /api/ota "web"): a mismatch = stale copy in the browser
        build = hashlib.sha1(data).hexdigest()[:12]
        data = data.replace(b"<head>", b"<head><script>window.SLINK_BUILD=\"" + build.encode() + b"\";</script>", 1)
    etag = hashlib.sha1(data).hexdigest()[:16]
    gz = not mime.startswith("image/png")          # text files travel gzip-compressed (321 KB -> ~100 KB over a weak WiFi); PNGs are compressed already
    if gz: data = gzip.compress(data, 9, mtime=0)  # mtime=0: the same input always gives the same bytes (no rebuild for nothing)
    lines += array("a%d" % n, data)
    table.append('  { "%s", "%s", "%s", "\\"%s\\"", a%d, %d, %d },' % (url, mime, cache, etag, n, len(data), 1 if gz else 0))
lines.append("const web_asset_t web_assets[] = {")
lines += table
lines.append("};")
lines.append("const size_t web_assets_n = %d;" % len(ASSETS))
lines.append('const char web_build[] = "%s";' % build)
text = "\n".join(lines) + "\n"

old = open(dst, encoding="utf-8").read() if os.path.exists(dst) else ""
if old != text:                         # do not touch the file (and trigger a rebuild) when nothing changed
    open(dst, "w", encoding="utf-8", newline="\n").write(text)
